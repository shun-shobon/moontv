import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src/caption/tables/generated.rs"
UNDEFINED = 0xFFFD


def u32_table(source: str, name: str, length: int) -> list[int]:
    body = re.search(rf"\b{name}\[\]\s*=\s*\{{(.*?)\}};", source, re.S)
    assert body, name
    values = [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", body.group(1))]
    assert len(values) == length, (name, len(values))
    return values


def char(code: int) -> str:
    return f"'\\u{{{code:x}}}'"


def char_array(name: str, doc: str, values: list[int]) -> str:
    lines = [", ".join(char(v) for v in values[i : i + 8]) + "," for i in range(0, len(values), 8)]
    body = "\n".join(f"    {line}" for line in lines)
    return f"/// {doc}\npub static {name}: [char; {len(values)}] = [\n{body}\n];\n"


def main() -> None:
    src = pathlib.Path(sys.argv[1])
    decoder = src / "src/decoder"
    conv = (decoder / "b24_conv_tables.hpp").read_text()
    gaiji = (decoder / "b24_gaiji_table.hpp").read_text()
    macros = (decoder / "b24_macros.hpp").read_text()
    drcs = (decoder / "b24_drcs_conv.cpp").read_text()
    sha = subprocess.run(["git", "-C", str(src), "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    license_comment = re.match(r"/\*(.*?)\*/", conv, re.S).group(1)
    license_text = "\n".join(re.sub(r"^\s*\* ?", "", line) for line in license_comment.strip().splitlines())

    kanji = u32_table(conv, "kKanjiTable", 94 * 94)
    alnum_full = u32_table(conv, "kAlphanumericTable_Fullwidth", 94)
    alnum_half = u32_table(conv, "kAlphanumericTable_Halfwidth", 94)
    hiragana = u32_table(conv, "kHiraganaTable", 94)
    katakana = u32_table(conv, "kKatakanaTable", 94)
    kana_half = u32_table(conv, "kKanaSymbolsTable_Halfwidth", 6)
    x0201_full = u32_table(conv, "kJISX0201KatakanaTable", 94)
    x0201_half = u32_table(conv, "kJISX0201KatakanaTable_Halfwidth", 94)
    kanji_half = u32_table(conv, "kKanjiSymbolsTable_Halfwidth", 188)
    additional = u32_table(gaiji, "kAdditionalSymbolsTable_Unicode", 940)

    # libaribcaption が中型の文字に施す置き換えと同じ組。
    pairs: dict[int, int] = {0x3000: 0x20}
    candidates = [
        *zip(kanji[:188], kanji_half),
        *zip(alnum_full, alnum_half),
        *zip(hiragana[0x79 - 0x21 :], kana_half),
        *zip(katakana[0x79 - 0x21 :], kana_half),
        *zip(x0201_full, x0201_half),
    ]
    for full, half in candidates:
        if full != half and UNDEFINED not in (full, half):
            pairs.setdefault(full, half)
    halfwidth = sorted(pairs.items())

    macro_rows = re.search(r"kDefaultMacros\[\]\[20\]\s*=\s*\{(.*?)\};", macros, re.S).group(1)
    default_macros = [
        [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", row) if int(v, 16) != 0]
        for row in re.findall(r"\{([^{}]*)\}", macro_rows)
    ]
    assert len(default_macros) == 16

    replacements: dict[str, int] = {}
    for key, value in re.findall(r'\{"([0-9a-f]{32})",\s*0x([0-9a-fA-F]+)\}', drcs):
        replacements.setdefault(key, int(value, 16))
    assert len(replacements) == 326, len(replacements)

    out = [
        "// @generated by scripts/gen-caption-tables.py. 手で編集しない。",
        f"// 出典: https://github.com/xqq/libaribcaption/tree/{sha}",
        "//",
        *[f"// {line}".rstrip() for line in license_text.splitlines()],
        "",
        char_array("KANJI", "漢字系集合の1〜84区（JIS X 0213 の1面）。添字は `(区 - 1) * 94 + (点 - 1)`。", kanji[: 84 * 94]),
        char_array("ADDITIONAL", "追加漢字（85〜86区）と追加記号（90〜94区）。添字は `(区 - 85) * 94 + (点 - 1)`。", additional),
        char_array("ALNUM", "英数集合（全角の字形）。", alnum_full),
        char_array("HIRAGANA", "平仮名集合。", hiragana),
        char_array("KATAKANA", "片仮名集合。", katakana),
        char_array("JIS_X0201_KATAKANA", "JIS X0201 片仮名集合（全角の字形）。", x0201_full),
        "/// 中型の文字に使う半角の字形。全角の文字で並べてある。",
        f"pub static HALFWIDTH: [(char, char); {len(halfwidth)}] = [",
        *[f"    ({char(f)}, {char(h)})," for f, h in halfwidth],
        "];",
        "",
        "/// 既定マクロ（0x60〜0x6F）。",
        "pub static DEFAULT_MACROS: [&[u8]; 16] = [",
        *["    &[" + ", ".join(f"0x{b:02x}" for b in row) + "]," for row in default_macros],
        "];",
        "",
        "/// DRCS のパターンデータの MD5 から置き換える文字。MD5 で並べてある。",
        f"pub static DRCS_REPLACEMENTS: [([u8; 16], char); {len(replacements)}] = [",
        *[
            "    ([" + ", ".join(f"0x{key[i : i + 2]}" for i in range(0, 32, 2)) + f"], {char(value)}),"
            for key, value in sorted(replacements.items())
        ],
        "];",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out))


main()
